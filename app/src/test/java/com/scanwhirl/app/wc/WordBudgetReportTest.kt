package com.scanwhirl.app.wc

import org.junit.After
import org.junit.AfterClass
import org.junit.Assert.assertEquals
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.File

/**
 * Lane WC, report mode: launch every main screen/state at 360x800dp, 100% font,
 * English with fictional fixtures, count the visible app-authored words, and
 * write build/reports/word_budget.md (screen | state | words | top 5 longest
 * strings). THIS TEST NEVER FAILS ON A COUNT - it is the baseline the enforcing
 * [WordBudgetGateTest] ratchets from. A screen that cannot be rendered is
 * recorded with its error, not thrown.
 *
 * Work is split across three lifecycle tests (each owns an [WcHarness] and
 * destroys every activity in finally, each bounded to 30 s). [writeReport] runs
 * once in @AfterClass from the accumulated rows, so JUnit method order cannot
 * affect the report.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35], qualifiers = "w360dp-h800dp-xxhdpi")
class WordBudgetReportTest {

    private lateinit var harness: WcHarness

    @Before
    fun setUp() {
        harness = WcHarness().also { it.setUp() }
    }

    @After
    fun tearDown() {
        harness.tearDown()
    }

    private fun group(part: Int) {
        val specs = harness.specs()
        val mine = specs.filterIndexed { i, _ -> i % PARTS == part }
        val rows = mine.map { harness.measure(it) }
        synchronized(ROWS) { ROWS.addAll(rows) }
    }

    @Test(timeout = 30_000)
    fun reportGroup0() = group(0)

    @Test(timeout = 30_000)
    fun reportGroup1() = group(1)

    @Test(timeout = 30_000)
    fun reportGroup2() = group(2)

    @Test
    fun `numeric values are not words`() {
        assertEquals(0, VisibleWords.wordsIn("1.6 MB").size)
        assertEquals(0, VisibleWords.wordsIn("200 x 230").size)
        assertEquals(0, VisibleWords.wordsIn("200 × 230 px · 32 KB").size)
        assertEquals(listOf("pages"), VisibleWords.wordsIn("5 pages"))
        assertEquals(2, VisibleWords.wordsIn("A/अ").size)
        assertEquals(5, VisibleWords.wordsIn("Too small: 1 KB · Try larger size").size)
    }

    companion object {
        private const val PARTS = 3
        private val ROWS = ArrayList<WcHarness.Row>()

        private fun cell(s: String) = s.replace("|", "/").replace("\n", " ")

        private fun markdown(): String {
            val sorted = synchronized(ROWS) { ROWS.toList() }
                .sortedWith(compareByDescending<WcHarness.Row> { it.words }
                    .thenBy { it.screen }.thenBy { it.state })
            val sb = StringBuilder()
            sb.appendLine("# ScanWhirl visible word budget (report mode)")
            sb.appendLine()
            sb.appendLine("Generated by `WordBudgetReportTest` - fictional fixtures, EN, 100% font, 360x800dp, SDK 35.")
            sb.appendLine("Counts app-authored words only: user-content marks are skipped, EditText hints only, numeric values excluded.")
            sb.appendLine()
            sb.appendLine("| Screen | State | Words | Top 5 longest strings |")
            sb.appendLine("|---|---|---:|---|")
            for (r in sorted) {
                val top = if (r.error != null) "NOT RENDERED: ${r.error}" else r.top.joinToString("<br>") { cell(it) }
                sb.appendLine("| ${cell(r.screen)} | ${cell(r.state)} | ${r.words} | $top |")
            }
            sb.appendLine()
            sb.appendLine("Screens measured: ${sorted.size}; over 40 words: ${sorted.count { it.words > 40 }}.")
            return sb.toString()
        }

        @JvmStatic
        @AfterClass
        fun writeReport() {
            val text = markdown()
            val base = File(System.getProperty("user.dir") ?: ".")
            // Gradle's test workingDir is the module dir in some versions and the repo
            // root in others; write to whichever build/reports tree exists.
            for (candidate in listOf(
                File(base, "build/reports/word_budget.md"),
                File(base, "app/build/reports/word_budget.md")
            )) {
                runCatching {
                    candidate.parentFile?.mkdirs()
                    candidate.writeText(text, Charsets.UTF_8)
                }
            }
            // The cloud gate only downloads test XML, not this file. Print it so the
            // report can be recovered from <system-out> of these tests.
            println("<<<WC_REPORT_BEGIN>>>")
            println(text)
            println("<<<WC_REPORT_END>>>")
        }
    }
}
