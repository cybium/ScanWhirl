#!/usr/bin/env python3
"""Generate small FICTIONAL fixtures for the uimap job (stdlib only).

Nothing binary is committed: the pre-push guard rejects .pdf/.png outside
reviewed asset folders, so every file is built on the runner at job time.
PDFs come from make_pdf.build(); PNGs use a tiny pure-stdlib PNG encoder
(IHDR/IDAT/IEND, filter 0) with a deterministic colour pattern so they are
never blank and pass the harness image-stats sanity check.

Usage: make_fixtures.py OUT_DIR
"""
import struct
import sys
import zlib
from pathlib import Path

from make_pdf import build

PDFS = {
    "fixture-invoice.pdf": [
        ["Fictional QA Invoice - SH-2026-041", "Sharma Traders (imaginary seller)", "Total: Rs. 2,450.00"],
        ["Page 2 of fictional invoice", "No real person or company is described here."],
    ],
    "fixture-letter.pdf": [
        ["Fictional QA Letter", "To: Asha Verma (fictional)", "Subject: Sample document for interface mapping"],
        ["Page 2 of fictional letter", "Generated by tools/e2e/make_fixtures.py"],
    ],
    "fixture-report-3p.pdf": [
        ["Fictional QA Report - page 1"],
        ["Fictional QA Report - page 2"],
        ["Fictional QA Report - page 3"],
    ],
}


def png(path, width=360, height=480):
    """Write a deterministic, non-blank RGB PNG without PIL."""
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type 0 (None)
        for x in range(width):
            r = (x * 7 + y * 3) % 256
            g = (x * 2 + y * 11) % 256
            b = (x + y * 5) % 256
            # a few broad bands guarantee colour variety at any sample step
            if (x // 40 + y // 40) % 2 == 0:
                r, g, b = (r + 60) % 256, (g + 30) % 256, (b + 90) % 256
            raw += bytes((r, g, b))

    def chunk(kind, body):
        c = struct.pack(">I", len(body)) + kind + body
        return c + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    data = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(bytes(raw), 6)) + chunk(b"IEND", b""))
    Path(path).write_bytes(data)
    return len(data)


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    out = Path(argv[1])
    out.mkdir(parents=True, exist_ok=True)
    for name, pages in PDFS.items():
        data = build(pages)
        (out / name).write_bytes(data)
        print("wrote", name, len(data), "bytes", len(pages), "pages")
    for name in ("fixture-photo.png", "fixture-id-back.png", "fixture-qr.png"):
        n = png(out / name)
        print("wrote", name, n, "bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
