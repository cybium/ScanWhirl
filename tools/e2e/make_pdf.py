#!/usr/bin/env python3
"""Write a tiny, valid, self-generated PDF fixture for the smoke test.

The PDF is written here so nothing binary has to be committed (the repo is
public and the pre-push guard rejects binaries outside reviewed asset folders).
The content is invented text only - no personal or licensed material.

Usage: make_pdf.py OUT.pdf "Label" ["second line" ...]
"""
import sys

PAGE_W, PAGE_H = 595, 842  # A4 at 72 dpi


def _escape(text):
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def build(pages):
    """pages: [[line, ...], ...] -> PDF bytes (one text block per page)."""
    count = len(pages)
    objects = {}
    objects[1] = b"<< /Type /Catalog /Pages 2 0 R >>"
    kids = " ".join("%d 0 R" % (4 + 2 * i) for i in range(count))
    objects[2] = ("<< /Type /Pages /Kids [%s] /Count %d >>" % (kids, count)).encode()
    objects[3] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
    for index, lines in enumerate(pages):
        page_id, content_id = 4 + 2 * index, 5 + 2 * index
        objects[page_id] = (
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] "
            "/Resources << /Font << /F1 3 0 R >> >> /Contents %d 0 R >>"
            % (PAGE_W, PAGE_H, content_id)
        ).encode()
        ops = ["BT", "/F1 22 Tf", "60 760 Td"]
        for line_no, line in enumerate(lines):
            if line_no:
                ops.append("0 -34 Td")
            ops.append("(%s) Tj" % _escape(line))
        ops.append("ET")
        stream = "\n".join(ops).encode()
        objects[content_id] = (
            ("<< /Length %d >>\nstream\n" % len(stream)).encode() + stream + b"\nendstream"
        )

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = {}
    for number in sorted(objects):
        offsets[number] = len(out)
        out += ("%d 0 obj\n" % number).encode() + objects[number] + b"\nendobj\n"
    highest = max(objects)
    xref = len(out)
    out += ("xref\n0 %d\n" % (highest + 1)).encode()
    out += b"0000000000 65535 f \n"
    for number in range(1, highest + 1):
        out += ("%010d 00000 n \n" % offsets[number]).encode()
    out += ("trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (highest + 1, xref)).encode()
    return bytes(out)


def main(argv):
    if len(argv) < 3:
        sys.stderr.write(__doc__)
        return 2
    path = argv[1]
    label = argv[2]
    extra = argv[3:]
    pages = [
        [label, "Generated by tools/e2e/make_pdf.py"] + extra,
        ["%s - page 2" % label, "Second page, generated fixture"],
    ]
    data = build(pages)
    with open(path, "wb") as handle:
        handle.write(data)
    print("wrote %s (%d bytes, %d pages)" % (path, len(data), len(pages)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
