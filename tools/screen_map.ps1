# Builds the coverage checklist of every screen, sheet and tool from the code (docs/audit/<date>/SCREEN_MAP.md).
# Every row must get a screenshot the lead has looked at and a verdict before a release.
param([string]$Out = "$PSScriptRoot\..\docs\audit\2026-11-14\SCREEN_MAP.md")
$root = Resolve-Path "$PSScriptRoot\.."
$java = Join-Path $root "app\src\main\java\com\scanwhirl\app"
[xml]$strings = Get-Content (Join-Path $root "app\src\main\res\values\strings.xml") -Encoding UTF8
$str = @{}
Get-ChildItem (Join-Path $root "app\src\main\res\values") -Filter 'strings*.xml' | ForEach-Object {
    [xml]$x = Get-Content $_.FullName -Encoding UTF8
    foreach ($s in $x.resources.string) { $str[$s.name] = $s.InnerText }
}
$lines = @("# Screen map: every screen, sheet and tool (coverage checklist)", "",
    "Generated by ``tools/screen_map.ps1`` from the code. A row is DONE only when the lead has LOOKED at its screenshot.",
    "Verdict: OK, or the defects found. Screenshots: ``C:\Users\Cybium\Desktop\ScanWhirl-HQ\qa\<run>\``.", "",
    "## 1. Screens (activities)", "", "| Screen | Reached from | Screenshot | Verdict |", "|---|---|---|---|")
[xml]$man = Get-Content (Join-Path $root "app\src\main\AndroidManifest.xml")
$ns = @{ a = "http://schemas.android.com/apk/res/android" }
Select-Xml -Xml $man -XPath "//activity" | ForEach-Object { $_.Node.GetAttribute("name", $ns.a) } | Sort-Object -Unique | ForEach-Object { $lines += "| ``$_`` |  |  |  |" }
$lines += @("", "## 2. Sheets and dialogs (by file, with title when static)", "", "| File | Sheet (title) | Screenshot | Verdict |", "|---|---|---|---|")
Get-ChildItem $java -Recurse -Filter *.kt | ForEach-Object {
    $rel = $_.FullName.Substring($java.Length + 1) -replace '\\', '/'
    $text = Get-Content $_.FullName -Raw
    $found = [regex]::Matches($text, 'SwSheet\.(builder|comingSoon)\([^)]*\)(?:[\s\S]{0,300}?\.setTitle\(\s*(?:getString\()?R\.string\.(\w+))?')
    foreach ($m in $found) {
        $title = if ($m.Groups[2].Success) { $str[$m.Groups[2].Value] } elseif ($m.Groups[1].Value -eq 'comingSoon') { "Coming soon (per tool)" } else { "(dynamic title)" }
        $lines += "| ``$rel`` | $title |  |  |"
    }
    foreach ($m in [regex]::Matches($text, 'AlertDialog\.Builder|MaterialAlertDialogBuilder')) { $lines += "| ``$rel`` | AlertDialog (legacy look) |  |  |" }
}
$lines += @("", "## 3. Tools (ToolRegistry)", "", "| Tool id | Status | Opens | Screenshot | Verdict |", "|---|---|---|---|---|")
$reg = Get-Content (Join-Path $java "ui\kit\ToolRegistry.kt") -Raw
foreach ($m in [regex]::Matches($reg, '(ready|soon|build)\("(\w+)"|id = "(\w+)"')) {
    $id = if ($m.Groups[2].Success) { $m.Groups[2].Value } else { $m.Groups[3].Value }
    $st = if ($m.Groups[1].Success) { $m.Groups[1].Value.ToUpper() } else { "READY" }
    $lines += "| ``$id`` | $st |  |  |  |"
}
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[IO.File]::WriteAllText($Out, ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding($false)))
"screens: $((Select-String -Path $Out -Pattern '^\| `\.ui').Count)  sheets: $((Select-String -Path $Out -Pattern '^\| `(ui|tools|store|util)/').Count)  tools: $((Select-String -Path $Out -Pattern '^\| `[a-z_]+` \| (READY|SOON|BUILD)').Count)"
